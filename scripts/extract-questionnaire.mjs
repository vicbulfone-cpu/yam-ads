// Copies the questionnaire wording and options from the old site (/source) into src/content/questionnaire.ts,
// so the questions, options and step order stay word-for-word. Run: node scripts/extract-questionnaire.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const src = (p) => readFileSync(join(root, "source", "src", p), "utf8");

const data = src("lib/questionnaireData.ts");
const start = data.indexOf("export interface SubOption");
const end = data.indexOf("export const getCategoryById");
if (start < 0 || end < 0) throw new Error("questionnaireData.ts layout changed; update the extractor.");
const block = data.slice(start, end).trimEnd();

// On-screen sentences of the first questionnaire page (GHLRedirectPage + CategorySubStep). Each one is checked
// against the old files below, so a typo here stops the script instead of reaching the site.
const ui = {
  progressBadge: "Your Match in Progress",
  introHeading: "We ask a couple more questions than most.",
  introText: "That’s how we match you perfectly the first time — so you don’t waste your time starting over with someone who isn’t quite right.",
  stepOf: "Step {n} of {total}",
  categoryOf: "Category {n} of {total}",
  smsfHelpBefore: "Choose just",
  smsfHelpStrong: "one option",
  smsfHelpAfter: "from either section below — that's all we need to match you with the right specialist.",
  defaultHelp: "Select all that apply — we’ll use these to match you with an accountant in your area who specialises in {category}.",
  otherBoxLabel: "Please let us know a little more detail",
  otherBoxPlaceholder: "Tell us what you need help with…",
  softwareHeading: "Which software do you need help with?",
  softwareError: "Please select a software package to continue",
  softwareErrorFull: "Please select a software package to continue.",
  smsfError: "Please select at least one option from either section to continue.",
  defaultError: "Please select at least one option to continue.",
  back: "Back",
  next: "Next",
};

const decode = (s) =>
  s.replace(/&mdash;/g, "—").replace(/&rsquo;/g, "’").replace(/&apos;/g, "'").replace(/\{" "\}/g, " ")
    .replace(/<[^>]+>/g, " ").replace(/\{\s*n\s*\}|\{stepNumber\}|\{categoryIndex \+ 1\}/g, "{n}")
    .replace(/\{totalSteps\}|\{totalCategories\}/g, "{total}").replace(/\{category\.label\.toLowerCase\(\)\}/g, "{category}")
    .replace(/\s+/g, " ");
const old = decode(src("pages/GHLRedirectPage.tsx") + " " + src("components/questionnaire/CategorySubStep.tsx") + " " + src("components/home/MatchSelectionCard.tsx"));
const missing = Object.entries(ui).filter(([, v]) => !old.includes(v.replace(/\s+/g, " ")));
if (missing.length) throw new Error("Not found in /source: " + missing.map(([k, v]) => `${k}: "${v}"`).join("; "));

const out = `// GENERATED by scripts/extract-questionnaire.mjs from source/src/lib/questionnaireData.ts and the old questionnaire
// screens. Do not edit by hand; re-run the script. Wording, options and order are the old site's, unchanged.

${block}

/** First-page wording of the old questionnaire (verified against /source by the extractor). */
export const QUESTIONNAIRE_UI = ${JSON.stringify(ui, null, 2)} as const;
`;
writeFileSync(join(root, "src", "content", "questionnaire.ts"), out);
console.log(`Wrote src/content/questionnaire.ts (${out.length} chars, ${Object.keys(ui).length} UI strings verified).`);
