// Builds docs/page-inventory.md and data/extracted/page-types.json from the extraction output.
// Run after `npm run extract`:  npm run inventory

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EX = path.join(ROOT, "data", "extracted");
const DOCS = path.join(ROOT, "docs");

// The 13 cities that will be built. `picture` is the file the user supplied in /assets.
export const CITIES = {
  sydney: { name: "Sydney", state: "NSW", region: "Greater Sydney", picture: "sydney.png" },
  "newcastle-maitland": { name: "Newcastle - Maitland", state: "NSW", region: "Hunter", picture: "newcastle midland.png" },
  melbourne: { name: "Melbourne", state: "VIC", region: "Greater Melbourne", picture: "melbourne.png" },
  geelong: { name: "Geelong", state: "VIC", region: "Barwon / Geelong region", picture: "geelong.png" },
  brisbane: { name: "Brisbane", state: "QLD", region: "South East Queensland", picture: "brisbane.png" },
  "gold-coast": { name: "Gold Coast", state: "QLD", region: "South East Queensland", picture: "gold coast.png" },
  "sunshine-coast": { name: "Sunshine Coast", state: "QLD", region: "Sunshine Coast", picture: "sunshine coast.png" },
  perth: { name: "Perth", state: "WA", region: "Greater Perth", picture: "perth.png" },
  adelaide: { name: "Adelaide", state: "SA", region: "Greater Adelaide", picture: "adelaide.png" },
  hobart: { name: "Hobart", state: "TAS", region: "Southern Tasmania", picture: "hobart.png" },
  launceston: { name: "Launceston", state: "TAS", region: "Northern Tasmania", picture: "launceston.png" },
  "canberra-queanbeyan": { name: "Canberra - Queanbeyan", state: "ACT / NSW", region: "Canberra region", picture: "Canberra – Queanbeyan.png" },
  darwin: { name: "Darwin", state: "NT", region: "Top End", picture: "darwin.png" },
};

const STATIC = {
  "/privacy": "legal",
  "/terms": "legal",
  "/about": "about",
  "/contact": "contact",
  "/how-it-works": "how-it-works",
  "/how-we-select-accountants": "how-we-select",
  "/guides": "guides-hub",
  "/blog": "blog-hub",
  "/locations": "locations-hub",
  "/ghl-redirect": "questionnaire",
  "/admin-login": "admin (not rebuilt)",
  "/admin-dashboard": "admin (not rebuilt)",
};

function classify(p) {
  const pathOnly = p.split("?")[0];
  if (pathOnly === "/") return { type: "homepage" };
  if (STATIC[pathOnly]) return { type: STATIC[pathOnly] };
  let m;
  if ((m = pathOnly.match(/^\/locations\/([^/]+)$/))) {
    return CITIES[m[1]] ? { type: "city", city: m[1] } : { type: "retired location (redirect)", city: m[1] };
  }
  if ((m = pathOnly.match(/^\/industry\/([^/]+)\/([^/]+)$/))) {
    return { type: "industry-city", industry: m[1], city: m[2], cityKnown: !!CITIES[m[2]] };
  }
  if (pathOnly.startsWith("/accountant/")) return { type: "service" };
  if (pathOnly.startsWith("/guide/")) return { type: "guide" };
  if (pathOnly.startsWith("/blog/")) return { type: "article (blog)" };
  return { type: "other" };
}

const cut = (s, n) => (s && s.length > n ? s.slice(0, n - 1) + "…" : s ?? "");
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

const index = JSON.parse(fs.readFileSync(path.join(EX, "index.json"), "utf8"));
const pages = index.map((i) => ({
  ...JSON.parse(fs.readFileSync(path.join(EX, "pages", i.slug + ".json"), "utf8")),
  ...classify(i.path),
}));

// Group by type
const byType = new Map();
for (const p of pages) {
  if (!byType.has(p.type)) byType.set(p.type, []);
  byType.get(p.type).push(p);
}

let md = "# Page inventory\n\n";
md += "_Generated by `npm run inventory` from the rendered pages of the old site (`/source`). Do not edit by hand._\n\n";
md += `Total pages recorded: **${pages.length}** (${pages.filter((p) => p.inSitemap).length} in the old sitemap, ${pages.filter((p) => !p.inSitemap).length} extra routes).\n\n`;

md += "## Page types and counts\n\n| Type | Count | In sitemap | Notes |\n|---|---:|---:|---|\n";
for (const [t, arr] of [...byType.entries()].sort((a, b) => b[1].length - a[1].length)) {
  md += `| ${t} | ${arr.length} | ${arr.filter((p) => p.inSitemap).length} | |\n`;
}

md += "\n## Cities (13 to be built) and their pictures\n\n";
md += "| City page | State | Region | Picture supplied in /assets | City page extracted | Industry pages |\n|---|---|---|---|---|---:|\n";
for (const [slug, c] of Object.entries(CITIES)) {
  const cityPage = pages.find((p) => p.type === "city" && p.city === slug);
  const ind = pages.filter((p) => p.type === "industry-city" && p.city === slug).length;
  md += `| /locations/${slug} | ${c.state} | ${c.region} | ${c.picture} | ${cityPage ? (cityPage.error ? "ERROR" : "yes") : "NO"} | ${ind} |\n`;
}
md += "\nNo suburb pages exist in the old site (suburbs appear only inside city pages), and none will be built.\n";

const retired = pages.filter((p) => p.type === "retired location (redirect)");
if (retired.length) {
  md += "\n## Retired locations (old redirects, to be kept)\n\n| Old URL | Redirects to |\n|---|---|\n";
  for (const p of retired) md += `| ${p.path} | ${p.redirectedTo ?? "(none detected)"} |\n`;
}

md += "\n## Every page\n";
for (const [t, arr] of [...byType.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  md += `\n### ${t} (${arr.length})\n`;
  for (const p of arr.sort((a, b) => a.path.localeCompare(b.path))) {
    md += `\n#### \`${p.path}\`\n\n`;
    if (p.error) { md += `- **EXTRACTION ERROR:** ${esc(p.error)}\n`; continue; }
    if (p.redirectedTo) md += `- **Redirects to:** ${p.redirectedTo}\n`;
    md += `- **In old sitemap:** ${p.inSitemap ? "yes" : "no"}\n`;
    md += `- **Title:** ${esc(p.title)}\n`;
    md += `- **Meta description:** ${esc(p.metaDescription)}\n`;
    md += `- **Canonical:** ${esc(p.canonical)}\n`;
    md += `- **Robots:** ${p.robots?.length ? esc(p.robots.join("; ")) : "(none)"}\n`;
    md += `- **hreflang:** ${p.hreflang?.length ? p.hreflang.map((h) => `${h.lang}=${h.href}`).join(", ") : "(none)"}\n`;
    if (p.city) md += `- **City/region:** ${p.city}${CITIES[p.city] ? ` — ${CITIES[p.city].state}, ${CITIES[p.city].region}` : ""}\n`;
    if (p.industry) md += `- **Industry:** ${p.industry}\n`;
    md += `- **Words on page:** ${p.allText ? p.allText.split(" ").length : 0}\n`;
    md += `- **Heading order:** ${p.headings.map((h) => `H${h.level} ${cut(h.text, 70)}`).join(" › ") || "(none)"}\n`;
    md += `- **Content blocks (${p.blocks.length}):** ${p.blocks.map((b) => `${b.tag}${b.heading ? ` “${cut(b.heading, 40)}”` : ""} (${b.text ? b.text.split(" ").length : 0}w, ${b.images} img)`).join("; ") || "(none)"}\n`;
    md += `- **Images (${p.images.length}):** ${p.images.map((i) => cut(i.src, 60)).join(", ") || "(none)"}\n`;
  }
}

fs.mkdirSync(DOCS, { recursive: true });
fs.writeFileSync(path.join(DOCS, "page-inventory.md"), md);
fs.writeFileSync(
  path.join(EX, "page-types.json"),
  JSON.stringify(
    pages.map((p) => ({ path: p.path, type: p.type, city: p.city ?? null, industry: p.industry ?? null, inSitemap: p.inSitemap, error: p.error ?? null })),
    null,
    2
  )
);
console.log(`Wrote docs/page-inventory.md (${pages.length} pages) and data/extracted/page-types.json`);
console.log([...byType.entries()].map(([t, a]) => `${t}: ${a.length}`).join("\n"));
